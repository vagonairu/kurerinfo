  return :transport if value.match?(/velosiped|avto|samokat|bike|peshij|termosum|termokorob|forma|велосипед|авто|самокат|пеш|термосум|термокороб/)
  return :comparison if value.match?(/-ili-|plyusy|minusy|otzyv|stoit-li|gde-luchshe|prichin| или |плюс|минус|отзыв|стоит ли|где лучше|причин/)
  return :onboarding if value.match?(/stat-kurier|registr|pervyj|start|bez-opyta|стать курьер|регистрац|первый|старт|без опыта/)
  return :money if value.match?(/zarab|dohod|plat|vyplat|bonus|koeff|chaev|karta|100000|зарабат|доход|платят|выплат|бонус|чаев|карта/)
