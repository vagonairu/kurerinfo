def split_document(raw)
  match = raw.match(/\A---\s*\n(.*?)\n---\s*\n?/m)
  raise "Не найден front matter" unless match

  [match[1], raw[match.end(0)..].to_s]
end

def choose(seed, offset, values)
  values[(seed + offset * 17) % values.length]
end

def tokens(text)
  text.downcase.scan(/[a-zа-яё0-9]+/).reject { |token| token.length < 4 || STOP_WORDS.include?(token) }.uniq
end

def compact_focus(title, keywords)
  candidate = Array(keywords).map(&:to_s).find { |item| item.length.between?(8, 62) }
  candidate || title.to_s.split(":").first.to_s.strip
end

