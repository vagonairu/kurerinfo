def related_records(record, all_records)
  own_tokens = tokens("#{record[:title]} #{record[:keywords].join(" ")}")
  ranked = all_records.reject { |candidate| candidate[:slug] == record[:slug] }.map do |candidate|
    candidate_tokens = tokens("#{candidate[:title]} #{candidate[:keywords].join(" ")}")
    overlap = (own_tokens & candidate_tokens).length
    same_profile = candidate[:profile_key] == record[:profile_key] ? 4 : 0
    tie = Zlib.crc32("#{record[:slug]}:#{candidate[:slug]}") % 1000 / 1000.0
    [overlap * 5 + same_profile + tie, candidate]
  end
  ranked.sort_by { |score, _candidate| -score }.first(6).map(&:last)
end

