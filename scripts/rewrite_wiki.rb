  value = "#{slug} #{title}".downcase
  return :city if value.match?(/millionnik|moskv|peterburg|ekaterinburg|novosibirsk|kazan|krasnodar|nizhn|samar|rostov|chelyab|ufe|omsk|permi|volgograd|krasnoyarsk|москов|петербург|казан|городах/)
