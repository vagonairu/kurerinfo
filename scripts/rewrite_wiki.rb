paths = Dir.glob(File.join(WIKI_DIR, "*.md")).reject { |path| File.basename(path) == "_index.md" }.sort
records = paths.map do |path|
  raw = File.read(path)
  front, _body = split_document(raw)
  data = YAML.safe_load(front, permitted_classes: [Date, Time], aliases: true) || {}
  slug = data["slug"].to_s
  slug = File.basename(path, ".md") if slug.empty?
  key = profile_key(slug, data["title"].to_s)
  {
    path: path,
    data: data,
    slug: slug,
    title: data["title"].to_s,
    keywords: Array(data["keywords"]).map(&:to_s),
    seed: Zlib.crc32(slug),
    profile_key: key,
    profile: PROFILES.fetch(key)
  }
end

records.each { |record| record[:focus] = compact_focus(record[:title], record[:keywords]) }
focus_counts = records.each_with_object(Hash.new(0)) { |record, counts| counts[record[:focus].downcase] += 1 }
records.each { |record| record[:focus_unique] = focus_counts[record[:focus].downcase] == 1 }

